local MODES = { auto = true, all = true }

function EJ.ej.FactionMode()
  local m = EJ.db and EJ.db.ejFaction
  return MODES[m] and m or "auto"
end

-- "Alliance" / "Horde" when filtering, nil when everything is shown.
function EJ.ej.ActiveFaction()
  if EJ.ej.FactionMode() == "all" then return nil end
  local f = UnitFactionGroup and UnitFactionGroup("player")
  if f == "Alliance" or f == "Horde" then return f end
  return nil
end

function EJ.ej.ApplyFaction()
  local fd, data = EJ.ej.FACTION_DATA, EJ.ej.DATA
  if not (fd and data and data.instances) then return end
  local fac = EJ.ej.ActiveFaction()
  local short = fac and fac:sub(1, 1)
  local encFac, itemFac = fd.encounters or {}, fd.items or {}
  for _, inst in ipairs(data.instances) do
    inst._ejAllEncounters = inst._ejAllEncounters or inst.encounters
    local all = inst._ejAllEncounters
    if all then
      local kept = {}
      for _, enc in ipairs(all) do
        if not fac or not encFac[enc.id] or encFac[enc.id] == fac then
          kept[#kept + 1] = enc
          enc._ejAllLoot = enc._ejAllLoot or enc.loot
          if enc._ejAllLoot then
            local loot = {}
            for _, e in ipairs(enc._ejAllLoot) do
              local id = (type(e) == "table") and e.id or e
              local f = id and itemFac[id]
              if not short or not f or f == short then loot[#loot + 1] = e end
            end
            enc.loot = loot
          end
        end
      end
      inst.encounters = kept
    end
  end
  if EJ.ej.ResetApiIndex then EJ.ej.ResetApiIndex() end
  if EJ.ej.ResetSearchIndex then EJ.ej.ResetSearchIndex() end
end

-- `/ej faction [auto|all]`
function EJ.ej.SetFactionMode(m)
  local cf = _G.DEFAULT_CHAT_FRAME
  if m and MODES[m] then
    if EJ.db then EJ.db.ejFaction = m end
    EJ.ej.ApplyFaction()
    local f = EJ.ej.frame
    if f and f:IsShown() and EJ.ej.ShowList then EJ.ej.ShowList() end
  elseif m and m ~= "" and cf then
    cf:AddMessage("|cff66ccffEncounterJournal|r unknown faction mode '" .. m .. "' (use auto or all)")
    return
  end
  if cf then
    local fac = EJ.ej.ActiveFaction()
    cf:AddMessage("|cff66ccffEncounterJournal|r faction filter: |cffffd200" .. EJ.ej.FactionMode() .. "|r"
      .. (fac and (" (showing " .. fac .. " bosses and loot)") or " (showing both factions)"))
  end
end
