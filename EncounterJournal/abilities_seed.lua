-- Hand-seeded VANILLA (Era 1.15) boss ability
-- sections for the instances retail's modern Encounter Journal never authored for the
-- Classic tier (every empty-section boss in Data.lua). Merged into EJ.ej.DATA at load by
-- encounter id WITHOUT editing the auto-generated Data.lua — same overlay mechanism as
-- PortraitOverrides.lua, so it survives a Data.lua re-gen. Must load AFTER Data.lua.
--
-- Why this exists (and why NOT from retail DB2): nearly every classic dungeon/raid that
-- lacks sections was REVAMPED in Cataclysm/MoP, so retail's modern EJ describes a different
-- roster (e.g. modern Shadowfang Keep = Ashbury/Godfrey/Walden, not Rethilgore/Arugal). The
-- raids (MC/BWL/AQ/Naxx/Onyxia) have no modern sections at all. Era versioning therefore
-- requires the VANILLA ability set, sourced from the live 1.15 data:
--   * which spells each boss casts  -> cmangos EventAI (creature_ai_scripts) / boss scripts
--   * each spell's school/dispel/mechanic/cast -> cmangos spell_template (== the 1.15 DBC)
--   * resolved tooltip values/durations -> Classic-Era Wowhead spell pages
-- Flag badges are DERIVED, not guessed: Magic(128)=dispel Magic, Curse(256)=dispel Curse,
-- Poison(512)=dispel Poison, Disease(1024)=dispel Disease, Enrage(2048)=self damage frenzy,
-- Interrupt(64)=has a real cast time and is silence-preventable, Healer(4)=heal, Tank(1),
-- Important(32)=summons/major mechanic. (Bit order per EncounterPage FLAG_ATLAS.)
--
-- Schema per entry: ABIL[encounterID] = { {title=, body=, flags=, spell=}, ... } — a flat
-- sibling list (top-level abilities). `spell` is the real vanilla spellID; the renderer
-- resolves its icon via GetSpellTexture at runtime (no baked FDID). Section ids are
-- synthesised as encID*1000 + index, unique within the boss.

