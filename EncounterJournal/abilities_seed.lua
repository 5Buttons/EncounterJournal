-- ===== APPLY =====

-- Fill section-less encounters (or every encounter in `force`) from `seed`. Unchanged from the three
-- per-tier copies this replaced: same synthetic ids, same field set.
local function apply(seed, force)
  local data = EJ.ej.DATA
  if not data then return end
  for _, inst in ipairs(data.instances or {}) do
    for _, enc in ipairs(inst.encounters or {}) do
      local list = seed[enc.id]
      if list and ((force and force[enc.id]) or not enc.sections or #enc.sections == 0) then
        local secs, n = {}, #list
        for i, a in ipairs(list) do
          secs[i] = {
            id = enc.id * 1000 + i, title = a.title, parent = 0, child = 0,
            sib = (i < n) and (enc.id * 1000 + i + 1) or 0, order = i,
            spell = a.spell or 0, icon = a.icon or 0, flags = a.flags or 0, cdisp = 0, body = a.body,
          }
        end
        enc.sections = secs
        enc.rootSection = secs[1] and secs[1].id or 0
      end
    end
  end
end
apply(VANILLA)
apply(TBC)
apply(WOTLK, FORCE)
