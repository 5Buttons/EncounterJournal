-- Addon/EncounterJournal/abilities_seed.lua - hand-seeded boss ability sections for every encounter the
-- retail DB2 extract carries none for, all three tiers in ONE overlay with ONE apply pass:
--   VANILLA  Classic dungeons + raids   (was the AbilitiesEra part of vanilla_data.lua)
--   TBC      the 8 Burning Crusade raids (was tbc_abilities.lua)
--   WOTLK    the WotLK raids + Ulduar   (was wotlk_abilities.lua; FORCE replaces the DB2 Ulduar entries)
-- Merged into EJ.ej.DATA at load, only into encounters that still have no sections (plus the WotLK
-- FORCE set), so a future DB2 regen that ships real sections wins automatically. Must load AFTER
-- every *_data.lua. Schema per entry: TIER[encounterID] = { {title=, body=, flags=, spell=}, ... };
-- section ids are synthesised as encID*1000 + index (unique within the boss). The three seed
-- tables share no encounter id (Classic ids are cmangos npc ids, BC/WotLK ids are JournalEncounter ids).

